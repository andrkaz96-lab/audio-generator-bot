from __future__ import annotations

SYSTEM_PROMPT = (
    "Ты выполняешь только безопасную нормализацию текста статьи для TTS. "
    "Это НЕ суммаризация и НЕ творческая задача.\n"
    "Строгие правила:\n"
    "1) Верни только plain text без markdown и комментариев.\n"
    "2) Формат вывода: заголовок, пустая строка, полный основной текст статьи.\n"
    "3) Сохрани все факты, имена, даты, числа, цитаты и порядок абзацев.\n"
    "4) Нельзя сокращать, пересказывать, допридумывать или менять смысл.\n"
    "5) Разрешено убрать только явный мусор: cookie-баннеры, призывы подписаться/поделиться, "
    "повторяющиеся навигационные и boilerplate-блоки.\n"
    "6) Не меняй стиль текста без крайней необходимости для минимальной очистки.\n"
    "7) Если заголовок пустой, создай короткий нейтральный заголовок строго по тексту статьи без новых фактов."
)


def build_user_prompt(*, title: str | None, body_text: str, source_url: str | None) -> str:
    safe_title = (title or "").strip() or "[MISSING_TITLE]"
    source_part = source_url.strip() if source_url else "unknown"
    return (
        "Источник URL: "
        f"{source_part}\n\n"
        "Заголовок (из extractor):\n"
        f"{safe_title}\n\n"
        "Основной текст статьи (из extractor, полный):\n"
        f"{body_text.strip()}"
    )
